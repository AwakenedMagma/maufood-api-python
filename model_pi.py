def get_menu_serupa(nama_menu, top_n=5):
    """
    Mengembalikan top-N menu paling mirip dengan `nama_menu` berdasarkan
    skor cosine similarity dari fitur Kategori/Bahan/Rasa.
    Item itu sendiri selalu dikeluarkan dari hasil.
    """
