"""### 5.5 EVALUASI PRECISION@K / RECALL@K (akurasi top-N rekomendasi)"""

print("=== 5. Evaluasi Precision@K & Recall@K (akurasi ranking top-N) ===")

def topk_rekomendasi(user_id, K, alpha, beta):
    sudah = set(uim.loc[user_id].dropna().index) if user_id in uim.index else set()
    kandidat = [i for i in all_items if i not in sudah]
    skor = []
    for item in kandidat:
        p_cf = prediksi_cf(user_id, item)
        s_cbf = cbf_affinity(user_id, item)
        p_cf_norm = max(0.0, min(1.0, p_cf / 5)) if p_cf is not None else 0.0
        skor.append((item, alpha * p_cf_norm + beta * s_cbf))
    skor.sort(key=lambda x: x[1], reverse=True)
    return [i for i, _ in skor[:K]]

# item "relevan" = pernah dipesan lagi di test set dengan rating >= 4
relevan = (df_test[df_test['Rating_Pelanggan'] >= 4]
           .groupby('User_ID')['ID_Menu'].apply(set).to_dict())
eligible_users = [u for u, r in relevan.items() if len(r) > 0]
print(f"Pelanggan dgn minimal 1 menu relevan (rating>=4) di test set: {len(eligible_users)} dari {uim.shape[0]}")

rng = random.Random(RANDOM_SEED)
K = 5

def evaluasi_topk(alpha=None, beta=None, metode='hybrid'):
    precisions, recalls = [], []
    for uid in eligible_users:
        rel = relevan[uid]
        if metode == 'random':
            rekom = rng.sample(all_items, K)
        else:
            rekom = topk_rekomendasi(uid, K, alpha, beta)
        hit = len(set(rekom) & rel)
        precisions.append(hit / K)
        recalls.append(hit / min(len(rel), K))
    return float(np.mean(precisions)), float(np.mean(recalls))

hasil_topk = []
for label, alpha, beta, metode in [
    ('Baseline: rekomendasi acak', None, None, 'random'),
    ('CF-only', 1.0, 0.0, 'hybrid'),
    ('Hybrid (alpha=0.6, beta=0.4)', 0.6, 0.4, 'hybrid'),
    (f'Hybrid tuned (alpha={ALPHA_OPTIMAL}, beta={BETA_OPTIMAL})', ALPHA_OPTIMAL, BETA_OPTIMAL, 'hybrid'),
]:
    p, r = evaluasi_topk(alpha, beta, metode)
    hasil_topk.append({'Metode': label, f'Precision@{K}': round(p, 4), f'Recall@{K}': round(r, 4)})

