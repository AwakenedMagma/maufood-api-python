"""### 3.4 PREDIKSI SKOR (User-Based CF)"""

def prediksi_rating(user_id, item_id, k=10):
    """
    Memprediksi skor (rating) yang kemungkinan akan diberikan `user_id`
    untuk `item_id`, berdasarkan rating item tersebut dari k pelanggan
    lain yang paling mirip (dan sudah pernah menilai item ini).

    Rumus: pred(u,i) = mean(u) + [ sum_v sim(u,v) * (r(v,i) - mean(v)) ]
                                   / sum_v |sim(u,v)|
    untuk v = tetangga (user lain) yang sudah menilai item i.
    """
    if user_id not in user_item_matrix.index or item_id not in user_item_matrix.columns:
        return None

    # user lain yang sudah pernah menilai item ini
    penilai = user_item_matrix[item_id].dropna().drop(index=user_id, errors='ignore')
    if len(penilai) == 0:
        return None  # tidak ada satu pun tetangga yang pernah menilai item ini

    sim_ke_penilai = user_sim_df.loc[user_id, penilai.index]
    sim_ke_penilai = sim_ke_penilai[sim_ke_penilai > 0]  # hanya tetangga yang "searah"
    if len(sim_ke_penilai) == 0:
        return None

    top_k = sim_ke_penilai.sort_values(ascending=False).head(k)
    pembilang = sum(
        top_k[v] * (user_item_matrix.loc[v, item_id] - user_means[v])
        for v in top_k.index
    )
    penyebut = sum(abs(s) for s in top_k)
    if penyebut == 0:
        return None
    return user_means[user_id] + pembilang / penyebut

"""### 3.5 FUNGSI REKOMENDASI TOP-N (CF)"""

def rekomendasi_cf(user_id, top_n=5, k=10):
    """
    Mengembalikan top-N menu dengan prediksi skor tertinggi untuk
    `user_id`, dari menu-menu yang BELUM pernah dia pesan.
    Mengembalikan None kalau user_id tidak dikenali sama sekali
    (khas kasus pelanggan baru/cold start -- CF tidak bisa menangani ini,
    harus dilempar ke CBF di Tahap 1).
    """
    if user_id not in user_item_matrix.index:
        print(f"[Cold Start] {user_id} tidak ada riwayat transaksi -- "
              "CF tidak bisa memprediksi apa pun. Gunakan CBF (Tahap 1).")
        return pd.DataFrame()

    sudah_dipesan = user_item_matrix.loc[user_id].dropna().index
    kandidat = [i for i in user_item_matrix.columns if i not in sudah_dipesan]

    hasil = []
    for item in kandidat:
        pred = prediksi_rating(user_id, item, k=k)
        if pred is not None:
            hasil.append((item, pred))

    hasil.sort(key=lambda x: x[1], reverse=True)
    hasil = hasil[:top_n]

    if not hasil:
        return pd.DataFrame()

    df_hasil = df_menu[df_menu['ID_Menu'].isin([i for i, _ in hasil])].copy()
    skor_map = dict(hasil)
    df_hasil['skor_prediksi'] = df_hasil['ID_Menu'].map(skor_map).round(2)
    df_hasil = df_hasil.sort_values('skor_prediksi', ascending=False)
    return df_hasil[['Nama_Menu', 'Kategori_Hidangan', 'Bahan_Baku',
                      'Rasa_Dominan', 'skor_prediksi']].reset_index(drop=True)


