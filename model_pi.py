"""### 5.2 LATIH ULANG CF DARI TRAIN SAJA"""

uim = df_train.pivot_table(index='User_ID', columns='ID_Menu', values='Rating_Pelanggan')
user_means = uim.mean(axis=1)
uim_centered = uim.sub(user_means, axis=0).fillna(0)
