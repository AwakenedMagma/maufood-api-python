"""### 4.2 SKOR CBF-AFFINITY (profil rasa pelanggan LAMA dari riwayatnya)"""

def cbf_affinity(user_id, candidate_item_id):
    """
    Seberapa cocok `candidate_item_id` dengan "selera" pelanggan lama,
    dihitung dari kemiripan konten (CBF) ke SEMUA menu yang pernah ia
    nilai, dibobot oleh rating yang ia beri (menu yang dinilai tinggi
    berpengaruh lebih besar ke profil selera dibanding yang dinilai
    rendah). Hasilnya tetap di rentang skor kemiripan 0-1.
    """
    riwayat = user_item_matrix.loc[user_id].dropna()
    if len(riwayat) == 0:
        return 0.0
    cand_idx = id_to_idx[candidate_item_id]
    total_skor = sum(rating * cos_sim[cand_idx, id_to_idx[item_id]]
                      for item_id, rating in riwayat.items())
    total_bobot = riwayat.sum()
    return total_skor / total_bobot if total_bobot > 0 else 0.0

"""### 4.3 WEIGHTED HYBRID (untuk pelanggan LAMA): gabung skor CF + CBF"""

def prediksi_cf(user_id, item_id, k=10):
    """Prediksi rating user-based dan CF."""
    penilai = user_item_matrix[item_id].dropna().drop(index=user_id, errors='ignore')
    if len(penilai) == 0:
        return None
    sim = user_sim_df.loc[user_id, penilai.index]
    sim = sim[sim > 0]
    if len(sim) == 0:
        return None
    top_k = sim.sort_values(ascending=False).head(k)
    pembilang = sum(top_k[v] * (user_item_matrix.loc[v, item_id] - user_means[v])
                     for v in top_k.index)
    penyebut = sum(abs(s) for s in top_k)
    return None if penyebut == 0 else user_means[user_id] + pembilang / penyebut


def rekomendasi_weighted_hybrid(user_id, top_n=5, alpha=0.6, beta=0.4, k=10):
    """
    WEIGHTED HYBRID untuk pelanggan lama:
      skor_akhir = alpha * skor_CF_ternormalisasi + beta * skor_CBF
    - skor_CF (hasil prediksi rating, skala ~1-5) dinormalisasi ke 0-1
      dengan dibagi 5, supaya sebanding dengan skor_CBF yang sudah 0-1.
    - Kalau CF tidak bisa memberi skor untuk suatu item (tidak ada
      tetangga yang pernah menilainya), sistem otomatis pakai CBF saja
      untuk item itu (alpha efektif jadi 0, beta jadi 1) -- ini bentuk
      graceful degradation, bukan error.
    Bobot default alpha=0.6, beta=0.4 mengikuti proporsi yang sama
    dengan modul hybrid PHP (`rekomendasi.php`) yang sudah berjalan di
    aplikasi, supaya konsisten satu sistem.
    """
    sudah_dipesan = user_item_matrix.loc[user_id].dropna().index
    kandidat = [i for i in user_item_matrix.columns if i not in sudah_dipesan]

    hasil = []
    for item_id in kandidat:
        skor_cbf = cbf_affinity(user_id, item_id)
        skor_cf_raw = prediksi_cf(user_id, item_id, k=k)

        if skor_cf_raw is not None:
            skor_cf_norm = max(0.0, min(1.0, skor_cf_raw / 5.0))
            skor_akhir = alpha * skor_cf_norm + beta * skor_cbf
            sumber = "CF+CBF"
        else:
            skor_akhir = skor_cbf
            sumber = "CBF (CF tidak tersedia utk item ini)"

        hasil.append((item_id, skor_akhir, sumber))

    hasil.sort(key=lambda x: x[1], reverse=True)
    hasil = hasil[:top_n]

    df_hasil = df_menu[df_menu['ID_Menu'].isin([i for i, _, _ in hasil])].copy()
    skor_map = {i: round(s, 3) for i, s, _ in hasil}
    sumber_map = {i: sb for i, _, sb in hasil}
    df_hasil['skor_hybrid'] = df_hasil['ID_Menu'].map(skor_map)
    df_hasil['sumber'] = df_hasil['ID_Menu'].map(sumber_map)
    df_hasil = df_hasil.sort_values('skor_hybrid', ascending=False)
    return df_hasil[['Nama_Menu', 'Kategori_Hidangan', 'Bahan_Baku',
                      'Rasa_Dominan', 'skor_hybrid', 'sumber']].reset_index(drop=True)

"""### 4.4 REKOMENDASI POPULER"""

def rekomendasi_populer(top_n=5):
    """
    Dipakai kalau pelanggan baru DAN belum sempat ditanya preferensinya
    sama sekali (mis. buru-buru). Murni dari rata-rata rating menu di
    seluruh riwayat transaksi -- tidak personal, tapi tetap lebih baik
    daripada tidak merekomendasikan apa-apa.
    """
    rata2 = (user_item_matrix.mean(axis=0)
             .sort_values(ascending=False).head(top_n))
    df_hasil = df_menu[df_menu['ID_Menu'].isin(rata2.index)].copy()
    df_hasil['skor_populer'] = df_hasil['ID_Menu'].map(rata2.round(2))
    return df_hasil.sort_values('skor_populer', ascending=False)[
        ['Nama_Menu', 'Kategori_Hidangan', 'Bahan_Baku', 'Rasa_Dominan', 'skor_populer']
    ].reset_index(drop=True)


def rekomendasi_dari_preferensi(kategori=None, bahan=None, rasa=None, top_n=5):
    """CBF murni dari preferensi yang diucapkan pelanggan baru (dari Tahap 1)."""
    bagian = [str(x).replace(' ', '_') for x in (kategori, bahan, rasa) if x]
    if not bagian:
        return pd.DataFrame()
    query_vec = tfidf.transform([' '.join(bagian)])
    from sklearn.metrics.pairwise import cosine_similarity as cs
    skor = cs(query_vec, tfidf_matrix).flatten()
    hasil = df_menu.copy()
    hasil['skor_kecocokan'] = skor.round(3)
    hasil = hasil.sort_values('skor_kecocokan', ascending=False).head(top_n)
    return hasil[['Nama_Menu', 'Kategori_Hidangan', 'Bahan_Baku',
                   'Rasa_Dominan', 'skor_kecocokan']].reset_index(drop=True)

"""### 4.5 FUNGSI UTAMA: SWITCHING HYBRID"""

def rekomendasi_hybrid(user_id=None, kategori=None, bahan=None, rasa=None,
                        top_n=5, alpha=0.6, beta=0.4):
    """
    Titik masuk tunggal yang dipanggil dari sisi aplikasi (mis. pelayan
    input di form pemesanan). Logika SWITCHING HYBRID ada persis di
    percabangan if/else di bawah ini:

      if pelanggan dikenali & punya riwayat transaksi:
          -> WEIGHTED HYBRID (CF + CBF)
      elif pelanggan baru TAPI preferensi rasa/bahan/kategori sudah
           didapat lewat dialog (Conversational Recommender):
          -> CBF murni dari preferensi tsb
      else (pelanggan baru & belum ada info apa pun):
          -> rekomendasi populer (jaring pengaman)
    """
    # --- STATUS PELANGGAN ---
    is_pelanggan_lama = (user_id is not None) and (user_id in user_item_matrix.index)

    if is_pelanggan_lama:
        print(f"[Switching Hybrid] '{user_id}' = PELANGGAN LAMA "
              f"({len(user_item_matrix.loc[user_id].dropna())} riwayat transaksi) "
              f"-> WEIGHTED HYBRID (CF + CBF, alpha={alpha}, beta={beta})")
        return rekomendasi_hybrid_lama_atau_kosong(user_id, top_n, alpha, beta)

    elif kategori or bahan or rasa:
        print(f"[Switching Hybrid] Pelanggan BARU (cold start), preferensi sudah "
              f"didapat lewat dialog pelayan (Conversational Recommender): "
              f"kategori={kategori}, bahan={bahan}, rasa={rasa} -> CBF murni")
        return rekomendasi_dari_preferensi(kategori, bahan, rasa, top_n)

    else:
        print("[Switching Hybrid] Pelanggan BARU (cold start), preferensi belum "
              "sempat ditanyakan -> fallback rekomendasi POPULER")
        return rekomendasi_populer(top_n)


def rekomendasi_hybrid_lama_atau_kosong(user_id, top_n, alpha, beta):
    hasil = rekomendasi_weighted_hybrid(user_id, top_n, alpha, beta)
    if hasil.empty:
        return rekomendasi_populer(top_n)
    return hasil

